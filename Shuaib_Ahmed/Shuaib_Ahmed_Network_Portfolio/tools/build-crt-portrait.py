"""Encode the hero portrait as a compact luminance grid for the CRT renderer.

The source photo stays outside the published site; only the derived grid is written.
"""
from pathlib import Path
import argparse
import base64
import json
import zlib

import cv2
import numpy as np

SITE = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = SITE.parents[1] / "File_in_progress" / "crt-portrait" / "shuaib-source.jpeg"
GRID = (240, 300)
# Crop in source pixels, centered on the face; columns beyond the photo are empty screen.
CROP = (240, 15, 660, 540)
FACE = (462, 225)


def subject_mask(image):
    lightness = cv2.cvtColor(image, cv2.COLOR_BGR2LAB)[..., 0]
    mask = np.full(lightness.shape, cv2.GC_PR_BGD, np.uint8)
    mask[lightness < 95] = cv2.GC_PR_FGD
    mask[:, :8] = mask[:8, :] = cv2.GC_BGD
    mask[lightness > 200] = cv2.GC_BGD
    mask[150:300, 400:500] = cv2.GC_FGD
    mask[380:800, 200:480] = cv2.GC_FGD
    mask[232:400, 492:576] = cv2.GC_BGD  # pale phone case
    cv2.setRNGSeed(7)
    cv2.grabCut(image, mask, None, np.zeros((1, 65)), np.zeros((1, 65)), 6, cv2.GC_INIT_WITH_MASK)
    fg = np.where((mask == cv2.GC_FGD) | (mask == cv2.GC_PR_FGD), 255, 0).astype(np.uint8)
    fg = cv2.morphologyEx(fg, cv2.MORPH_OPEN, np.ones((5, 5), np.uint8))
    count, labels, stats, _ = cv2.connectedComponentsWithStats(fg)
    fg = np.where(labels == 1 + np.argmax(stats[1:, cv2.CC_STAT_AREA]), 255, 0).astype(np.uint8)
    flood = fg.copy()
    cv2.floodFill(flood, np.zeros((fg.shape[0] + 2, fg.shape[1] + 2), np.uint8), (0, 0), 255)
    return fg | cv2.bitwise_not(flood)


def encode(source):
    image = cv2.imread(str(source))
    if image is None:
        raise SystemExit(f"Cannot read portrait source: {source}")
    mask = cv2.GaussianBlur(subject_mask(image), (0, 0), 2.2).astype(np.float32) / 255
    gray = cv2.cvtColor(image, cv2.COLOR_BGR2LAB)[..., 0]
    gray = cv2.createCLAHE(clipLimit=2.4, tileGridSize=(6, 6)).apply(gray).astype(np.float32)
    gray = cv2.addWeighted(gray, 1.7, cv2.GaussianBlur(gray, (0, 0), 3), -0.7, 0)
    height, width = gray.shape
    ys, xs = np.mgrid[0:height, 0:width].astype(np.float32)
    # Fade the shoulders into the dark screen so only the head and collar read clearly.
    reach = np.hypot((xs - FACE[0]) / 250, (ys - FACE[1]) / 330)
    falloff = np.clip((1.12 - reach) / 0.42, 0, 1) ** 1.6
    # Soften the photo's right border and the edge left where the phone was removed.
    edge = np.clip((width - 10 - xs) / 70, 0, 1)
    rows = np.clip((ys - 200) / 45, 0, 1) * np.clip((520 - ys) / 50, 0, 1)
    phone = 1 - (1 - np.clip((498 - xs) / 30, 0, 1)) * rows
    alpha = mask * falloff * edge * phone
    inside = alpha > 0.05
    low, high = np.percentile(gray[inside], [2, 98.5])
    tone = np.clip((gray - low) / (high - low), 0, 1) ** 0.82
    # Dim the chest and hand below the chin so the face stays the brightest area.
    tone *= 1 - 0.68 * np.clip((ys - 315) / 120, 0, 1) ** 0.8
    x0, y0, x1, y1 = CROP
    canvas = np.zeros((y1 - y0, x1 - x0), np.float32)
    weight = np.zeros_like(canvas)
    sx1, sy1 = min(x1, width), min(y1, height)
    canvas[: sy1 - y0, : sx1 - x0] = (tone * alpha)[y0:sy1, x0:sx1]
    weight[: sy1 - y0, : sx1 - x0] = alpha[y0:sy1, x0:sx1]
    canvas = cv2.resize(canvas, GRID, interpolation=cv2.INTER_AREA)
    weight = cv2.resize(weight, GRID, interpolation=cv2.INTER_AREA)
    grid = np.where(weight > 0.04, 1 + np.round(canvas * 254), 0).astype(np.uint8)
    return grid


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--preview", type=Path)
    args = parser.parse_args()
    grid = encode(args.source)
    packed = base64.b64encode(zlib.compress(grid.tobytes(), 9)).decode("ascii")
    data = {"width": GRID[0], "height": GRID[1], "encoding": "zlib-base64", "data": packed}
    out = SITE / "assets" / "js" / "crt-portrait-data.js"
    out.write_text("/* Generated by tools/build-crt-portrait.py: luminance grid, 0 = empty screen. */\n"
                   f"window.PORTFOLIO_PORTRAIT = {json.dumps(data, separators=(',', ':'))};\n", encoding="utf-8")
    if args.preview:
        cv2.imwrite(str(args.preview), cv2.resize(grid, (GRID[0] * 2, GRID[1] * 2), interpolation=cv2.INTER_NEAREST))
    print(json.dumps({"grid": GRID, "inside": round(float((grid > 0).mean()), 3), "bytes": out.stat().st_size}))


if __name__ == "__main__":
    main()
