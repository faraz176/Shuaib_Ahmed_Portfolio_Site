"""Draw code-native network appliance glyphs and encode them for the existing CRT renderer."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFilter
import base64, json, zlib

SITE=Path(__file__).resolve().parents[1]

def appliance(kind):
    im=Image.new('L',(480,600),0); d=ImageDraw.Draw(im)
    # A rack appliance in three-quarter view. Luminance, rather than baked color, feeds the phosphor shader.
    d.polygon([(44,294),(342,246),(440,294),(142,350)],fill=95,outline=205)
    d.polygon([(44,294),(142,350),(142,412),(44,352)],fill=75,outline=155)
    d.polygon([(142,350),(440,294),(440,360),(142,412)],fill=140,outline=240)
    d.line([(54,301),(54,345),(132,390)],fill=205,width=2)
    for x in range(90,270,18):
        d.line([(x,289),(x+58,318)],fill=135,width=2)
    # Front ports use the face's perspective, with lit link indicators.
    count=12 if kind=='switch' else 4
    for i in range(count):
        x=157+i*(19 if kind=='switch' else 47)
        y=354-(x-142)*.188
        for row in range(2 if kind=='switch' else 1):
            yy=y+row*22
            w=15 if kind=='switch' else 32
            d.polygon([(x,yy),(x+w,yy-w*.188),(x+w,yy+14-w*.188),(x,yy+14)],fill=12,outline=210)
            d.line([(x+3,yy+10),(x+w-3,yy+10-(w-6)*.188)],fill=115,width=2)
            d.ellipse((x+3,yy-6,x+6,yy-3),fill=255)
    if kind=='router':
        # The familiar four-direction routing emblem is engraved into the top face.
        d.ellipse((192,273,280,312),fill=48,outline=230,width=2)
        d.line((208,293,263,293),fill=255,width=3); d.line((237,280,237,306),fill=255,width=3)
        d.polygon([(208,293),(220,287),(220,299)],fill=255)
        d.polygon([(263,293),(251,287),(251,299)],fill=255)
        d.polygon([(237,280),(229,287),(245,287)],fill=255)
        d.polygon([(237,306),(229,299),(245,299)],fill=255)
        for x in (370,398):
            y=357-(x-142)*.188
            d.rectangle((x,y,x+18,y+16),fill=25,outline=220,width=2)
    else:
        # Four switching paths distinguish the port-dense L2 chassis from the router.
        for y in (278,290,302):
            d.line((200,y,270,y-11),fill=230,width=2)
            d.polygon([(270,y-11),(262,y-16),(262,y-6)],fill=255)
    # A soft luminance halo is part of the input, then the shader supplies the blue/cyan bloom.
    im=Image.blend(im,im.filter(ImageFilter.GaussianBlur(1.4)),.18)
    return im.resize((240,300),Image.Resampling.LANCZOS)

channels=[]
for kind in ['router','switch']:
    image=appliance(kind)
    channels.append({'name':kind.upper(),'width':240,'height':300,'encoding':'zlib-base64','data':base64.b64encode(zlib.compress(image.tobytes(),9)).decode('ascii')})
(SITE/'assets/js/crt-channels-data.js').write_text('/* Generated by tools/build-crt-channels.py. */\nwindow.PORTFOLIO_CHANNELS='+json.dumps(channels,separators=(',',':'))+';\n',encoding='utf-8')
print(json.dumps({'channels':len(channels),'bytes':(SITE/'assets/js/crt-channels-data.js').stat().st_size}))
